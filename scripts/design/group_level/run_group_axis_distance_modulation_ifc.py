def _sha(path: Path) -> str:
    """Hash exact retained or generated bytes for the output manifest."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _read(path: Path) -> Any:
    """Read one JSON artifact without changing its contents."""
    return json.loads(path.read_text(encoding="utf-8"))


def _compatibility_binding(envelopes, raw, report: dict[str, Any]) -> dict[str, Any]:
    """Bind explicit registration facts to the actual supplied sources and channels."""
    group_ids = tuple(sorted(source.target["id"] for source in envelopes))
    axis_member_refs = {}
    for source in envelopes:
        axis_record = next(record for record in source.value["channels"] if record.channel == "overall_group_axis")
        axis_member_refs[source.target["id"]] = tuple(sorted({
            item["original_source_id"] for item in axis_record.observation.get("member_bindings", ())
            if item.get("status") == "accepted"
        }))
        if source.cache_identity["input_fingerprint"] != report["authentication"]["axis_source_sha256"]:
            raise ValueError("axis envelope does not retain the authenticated original IFC source")
    distance_member_refs = {group_id: set() for group_id in group_ids}
    raw_distance = {item.target["identity"]: item for item in raw.outputs if item.channel == "euclidean_distance"}
    if len(raw_distance) != 666:
        raise ValueError("authenticated distance output must contain all 666 Euclidean pairs")
    raw_sources = {item.target["identity"]: item for item in raw.source_envelopes}
    for pair_id, item in raw_distance.items():
        source = raw_sources[pair_id]
        source_record = next(record for record in source.value["channels"]
                             if isinstance(record.observation, Mapping) and "geometry_audit" in record.observation)
        audit = source_record.observation["geometry_audit"]
        for group_id, geometry in audit.items():
            distance_member_refs[group_id].update(geometry["source_refs"])
    distance_member_refs = {key: tuple(sorted(value)) for key, value in distance_member_refs.items()}
    query = next(iter(raw_distance.values())).provenance["query_context"]
    plane = next(iter(raw_distance.values())).provenance["analysis_plane"]
    if any(item.provenance["query_context"] != query or item.provenance["analysis_plane"] != plane
           for item in raw_distance.values()):
        raise ValueError("distance channels do not share one current query and projection plane")
    if set(distance_member_refs) != set(group_ids) or any(
        set(axis_member_refs[key]) != set(distance_member_refs[key]) for key in group_ids
    ):
        raise ValueError("distance and axis inputs do not retain the same original furniture members")
    if report["scope"]["groups"] != len(group_ids) or report["scope"]["unique_furniture"] != 95:
        raise ValueError("compatibility report does not cover the authenticated 37-group/95-member scope")
    if report["numerical_summary"]["mutual_coverage_at_distance_tolerance_count"] != 37:
        raise ValueError("compatibility report does not confirm registration for all 37 groups")
    return {
        "schema": report["schema"], "axis_source_sha256": report["authentication"]["axis_source_sha256"],
        "original_source_sha256": report["authentication"]["distance_input_hashes"]["original_ifc"],
        "group_ids": group_ids, "axis_member_refs": axis_member_refs,
        "distance_member_refs": distance_member_refs,
        "axis_plane": _json_value(envelopes[0].query.plane), "distance_plane": plane,
        "distance_query": query, "in_plane_origin_delta_m": tuple(report["coordinate_mapping"]["origin_delta_in_plane_m"]),
        "coordinate_mapping": report["coordinate_mapping"]["proof"],
        "registration_tolerance_m": 0.001,
        "mutual_body_coverage_count": report["numerical_summary"]["mutual_coverage_at_distance_tolerance_count"],
        "geometry_estimands_distinct": True,
        "source_registration": "original IFC group and 95 member identities; Body unions mutually covered at distance tolerance",
    }


def load_modulation_inputs():
    """Authenticate both retained packages and current processed recipe context."""
    if _sha(COMPATIBILITY) != COMPATIBILITY_SHA256:
        raise ValueError("retained distance/axis compatibility report hash mismatch")
    report = _read(COMPATIBILITY)
    inputs = retained.load_experiment_inputs()
    raw = load_saved_evidence_package(retained.PACKAGE_PATH, expected_sha256=retained.EXPECTED_HASHES["package"])
    axis_payload = _read(AXIS_REPLAY / "envelopes.json")
    envelopes = tuple(_load_envelope(item) for item in axis_payload["envelopes"])
    for name, digest in AXIS_HASHES.items():
        if _sha(AXIS_REPLAY / name) != digest:
            raise ValueError(f"retained axis replay hash mismatch: {name}")
    compatibility = _compatibility_binding(envelopes, raw, report)
    scope = tuple(sorted(item.target["identity"] for item in raw.outputs if item.channel == "euclidean_distance"))
    processor = build_euclidean_symmetric_reciprocal_proximity_processor(expected_target_ids=scope)
    fresh_processed = build_group_distance_evidence_package(output_processor=processor).process_output(
        raw, package_freshness=inputs.package_freshness,
    )
    if fresh_processed.error_code is not None or fresh_processed.processing_identity != processed_cache_key(raw, processor):
        raise ValueError("current symmetric-reciprocal processor did not produce its expected current recipe")
    contract = _read(retained.PACKAGE_PATH.parent / "package_contract.json")
    with tempfile.TemporaryDirectory(prefix="distance-potential-processed-") as temporary:
        path = Path(temporary) / "processed.json"
        path.write_text(json.dumps(serialize_evidence_processed_output(fresh_processed), sort_keys=True), encoding="utf-8")
        selected = consume_saved_evidence_package(
            retained.PACKAGE_PATH, expected_sha256=retained.EXPECTED_HASHES["package"],
            cached_contract=contract, current_contract=contract,
            current_source_envelopes=raw.source_envelopes,
            selections=tuple((identity, "euclidean_distance") for identity in scope),
            dependency_graph={"evidence-package-channel-readback": (raw.package_id,), raw.package_id: ()},
            processed_path=path, expected_processed_sha256=_sha(path),
            current_processing_identity=processed_cache_key(raw, processor),
            processed_selections=tuple((identity, CHANNEL, "verified_distance_copy") for identity in scope),
        )
    if selected.dependencies[0].package_freshness != "fresh" or selected.dependencies[1].package_freshness != "fresh":
        raise ValueError("saved consumer rejected the current raw or processed distance dependency")
    refs = tuple(reference for dependency in selected.dependencies for reference in dependency.channels
                 if reference.port == "processed")
    dependency = EvidencePackageDependency(
        package_id=raw.package_id, output_identity=raw.output_identity, channels=refs,
        source_output=raw, source_processed_output=fresh_processed, package_freshness="fresh",
    )
    graph = {"group-axis-potential": (raw.package_id,), raw.package_id: ()}
    modulation = DistanceModulationInput(dependency, processed_cache_key(raw, processor), compatibility, graph)
    return inputs, envelopes, raw, fresh_processed, modulation, report


def _rows(raw, processed, result) -> list[dict[str, Any]]:
    """Join each full axis cell to its anchor-target distance and modulation."""
    distance = {item.target["identity"]: item for item in raw.outputs if item.channel == "euclidean_distance"}
    proximity = {item.target["identity"]: item for item in processed.outputs if item.channel == CHANNEL}
    modulated = {(item.target["identity"], item.channel): item for item in result.outputs
                 if item.channel == "distance_modulated_axis_support"}
    rows = []
    for axis in result.outputs:
        if axis.channel != "axis_field_support":
            continue
        record = axis.observation
        anchor, group = record["anchor_group_id"], record["target_group_id"]
        if anchor == group:
            pair_id = None
            distance_value = proximity_value = None
            upstream_ref = None
        else:
            pair = next(item for item in distance.values()
                        if set(item.observation["group_ids"]) == {anchor, group})
            pair_id = pair.target["identity"]
            distance_value = pair.observation["value"]
            p = proximity[pair_id]
            proximity_value = p.observation
            upstream_ref = next(ref for ref in p.derived_from if ref.target_identity == pair_id)
        output = modulated[(axis.target["identity"], "distance_modulated_axis_support")]
        rows.append({
            "field_id": record["field_id"], "anchor_group_id": anchor, "group_id": group,
            "axis_support": record["axis_field_support"], "pair_id": pair_id,
            "distance_m": distance_value, "proximity": proximity_value,
            "distance_modulated_axis_support": output.observation,
            "status": output.status.value, "reason": output.explanation or None,
            "axis_lineage": [_json_value(ref) for ref in axis.derived_from],
            "processed_distance_lineage": None if upstream_ref is None else _json_value(upstream_ref),
        })
    if len(rows) != 37 * 37:
        raise ValueError("real-IFC diagnostic did not retain the complete 37 x 37 matrix")
    return rows


def _draw_contrast(rows, geometries, output_dir: Path) -> dict[str, Any]:
    """Render S, p and M on actual retained whole-group projected footprints."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.cm import ScalarMappable
    from matplotlib.colors import Normalize
    from matplotlib.patches import Polygon

    by_field: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        by_field.setdefault(row["field_id"], []).append(row)
    field = max(by_field, key=lambda field_id: (
        max((item["distance_modulated_axis_support"] or 0) for item in by_field[field_id]) -
        min((item["distance_modulated_axis_support"] or 0) for item in by_field[field_id]), field_id,
    ))
    selected = by_field[field]
    anchor = selected[0]["anchor_group_id"]
    group_ids = sorted(geometries)
    cmap = plt.get_cmap("cividis")
    fig, axes = plt.subplots(1, 3, figsize=(18, 8), constrained_layout=True)
    for axis, key, title in zip(axes, ("axis_support", "proximity", "distance_modulated_axis_support"),
                                ("Existing axis support S", "Accepted Euclidean proximity p", "Diagnostic M = S x p")):
        values = {row["group_id"]: row[key] for row in selected}
        for group_id in group_ids:
            geometry = geometries[group_id]
            value = values[group_id]
            fill = "#d8d8d8" if value is None else cmap(Normalize(0, 1)(value))
            polygons = tuple(geometry.geoms) if hasattr(geometry, "geoms") else (geometry,)
            for polygon in polygons:
                axis.add_patch(Polygon(list(polygon.exterior.coords), closed=True, facecolor=fill,
                                       edgecolor="#333333", linewidth=0.35))
                for ring in polygon.interiors:
                    axis.add_patch(Polygon(list(ring.coords), closed=True, facecolor="white",
                                           edgecolor="#777777", linewidth=0.25))
            center = geometry.centroid
            axis.text(center.x, center.y, f"{group_ids.index(group_id)+1:02d}", ha="center", va="center",
                      fontsize=7, color="#111111" if value is None or value < .5 else "white")
        axes_title = f"{title}\nanchor {group_ids.index(anchor)+1:02d}; fixed display range [0, 1]"
        axis.set(title=axes_title, xlabel="Analysis-plane X (m)", ylabel="Analysis-plane Y (m)", aspect="equal")
        axis.autoscale_view()
        axis.margins(0.04)
    fig.colorbar(ScalarMappable(norm=Normalize(0, 1), cmap=cmap), ax=list(axes),
                 fraction=0.025, pad=0.02, label="Observed value [0, 1]; gray means unavailable/self")
    fig.suptitle("Authenticated retained IFC; same original field and group footprints", fontsize=13)
    path = output_dir / "same_source_contrast.png"
    fig.savefig(path, dpi=160, bbox_inches="tight")
    plt.close(fig)
    return {"path": path.name, "field_id": field, "anchor_group_id": anchor,
            "group_order": group_ids, "color_range": [0, 1], "geometry": "retained whole-height Body union projections"}


def _write_outputs(output_dir, rows, inputs, raw, processed, result, modulation, report):
    """Write a complete indexed matrix, all-pair table, contrast view and manifest."""
    groups = sorted(inputs.geometries)
    json_path = output_dir / "distance_modulated_matrix.json"
    json_path.write_text(json.dumps({"schema": "distance-modulated-axis-matrix/1", "group_ids": groups,
                                     "cells": rows}, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    csv_path = output_dir / "distance_modulated_matrix.csv"
    fields = ["field_id", "anchor_group_id", "group_id", "axis_support", "pair_id", "distance_m",
              "proximity", "distance_modulated_axis_support", "status", "reason", "axis_lineage",
              "processed_distance_lineage"]
    with csv_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({**row, "axis_lineage": json.dumps(row["axis_lineage"], sort_keys=True),
                             "processed_distance_lineage": json.dumps(row["processed_distance_lineage"], sort_keys=True)})
    pair_path = output_dir / "distance_pair_table.csv"
    distance_by_target = {item.target["identity"]: item for item in raw.outputs if item.channel == "euclidean_distance"}
    processed_by_target = {item.target["identity"]: item for item in processed.outputs if item.channel == CHANNEL}
    with pair_path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=("pair_id", "group_a_id", "group_b_id", "distance_m", "proximity", "status", "lineage"))
        writer.writeheader()
        for pair_id, distance in sorted(distance_by_target.items()):
            item = processed_by_target[pair_id]
            writer.writerow({"pair_id": pair_id, "group_a_id": distance.observation["group_ids"][0],
                             "group_b_id": distance.observation["group_ids"][1],
                             "distance_m": distance.observation["value"], "proximity": item.observation,
                             "status": item.status.value, "lineage": json.dumps([_json_value(ref) for ref in item.derived_from], sort_keys=True)})
    visual = _draw_contrast(rows, inputs.geometries, output_dir)
    html_path = output_dir / "index.html"
    headers = "".join(f"<th>{html.escape(group)}</th>" for group in groups)
    cells = {row["field_id"]: row for row in rows}
    body = []
    for field in sorted({row["field_id"] for row in rows}, key=lambda value: next(row["anchor_group_id"] for row in rows if row["field_id"] == value)):
        anchor = next(row["anchor_group_id"] for row in rows if row["field_id"] == field)
        line = []
        for group in groups:
            row = next(item for item in rows if item["field_id"] == field and item["group_id"] == group)
            value = row["distance_modulated_axis_support"]
            color = "#dddddd" if value is None else f"#{int(239-130*value):02x}{int(246-170*value):02x}{int(255-116*value):02x}"
            line.append(f'<td title="S={row["axis_support"]}; p={row["proximity"]}; status={row["status"]}; reason={row["reason"]}" style="background:{color}">{"NA" if value is None else f"{value:.4f}"}</td>')
        body.append(f'<tr><th>{html.escape(anchor)}</th>{"".join(line)}</tr>')
    html_path.write_text("<!doctype html><meta charset=utf-8><title>Distance-modulated axis diagnostic</title>"
        "<style>body{font:13px system-ui;margin:24px;color:#222}table{border-collapse:collapse;font-size:10px}th,td{border:1px solid #bbb;padding:4px;text-align:right}th{position:sticky;top:0;background:#fff}img{max-width:100%}</style>"
        "<h1>Distance-modulated axis diagnostic</h1><p>Experimental size-neutral feasibility diagnostic M=S×p; no furniture-size weight is applied. Fixed [0,1] display. Gray NA includes self cells (distance_self_not_applicable).</p>"
        f'<p><a href="distance_modulated_matrix.csv">Complete 37×37 matrix CSV</a> · <a href="distance_pair_table.csv">All 666 unordered distance pairs</a> · <a href="distance_modulated_matrix.json">Indexed JSON and lineages</a></p><img src="same_source_contrast.png">'
        f'<table><thead><tr><th>Anchor / target</th>{headers}</tr></thead><tbody>{"".join(body)}</tbody></table>', encoding="utf-8")
    manifest = {
        "schema": "distance-potential-ifc-diagnostic-manifest/1",
        "experimental_formula": "M_d(g,k)=S(g,k)*p(g,anchor(k))",
        "processed_channel": CHANNEL,
        "processing_identity": modulation.current_processing_identity,
        "raw_distance_output_identity": raw.output_identity,
        "distance_processed_payload_fingerprint": processed.raw_payload_fingerprint,
        "potential_output_identity": result.output_identity,
        "compatibility_report": str(COMPATIBILITY), "compatibility_sha256": COMPATIBILITY_SHA256,
        "size_weight_applied": False,
        "interpretation": "Experimental size-neutral feasibility diagnostic; not a final size-aware model.",
        "source_hashes": {**inputs.input_hashes, **{f"axis_{name}": digest for name, digest in AXIS_HASHES.items()}},
        "source_binding": _json_value(inputs.source_binding),
        "original_axis_query": _json_value(result.source_envelopes[0].query),
        "distance_query_and_plane": _json_value(modulation.compatibility["distance_query"]),
        "coordinate_registration": _json_value(modulation.compatibility),
        "scope": {"groups": 37, "members": 95, "unordered_distance_pairs": 666, "directed_axis_cells": len(rows),
                  "computed_modulation_cells": sum(row["status"] == "computed" for row in rows),
                  "self_cells": sum(row["reason"] == "distance_self_not_applicable" for row in rows)},
        "visualization": visual,
        "artifacts": {path.name: _sha(path) for path in (json_path, csv_path, pair_path, html_path, output_dir / visual["path"])},
        "limits": ["Coordinate registration does not equate PCA Analysis and Body-centroid estimands or queries.",
                   "Freshness covers authenticated retained context; live scene currentness is not observed.",
                   "Diagnostic is not probability, production attenuation, cluster validity or independent evidence voting."],
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")
    return manifest


def run(output_root: Path = OUTPUT) -> Path:
    """Build the explicitly opted-in diagnostic from authenticated retained inputs."""
    inputs, envelopes, raw, processed, modulation, report = load_modulation_inputs()
    result = run_group_axis_potential_package(envelopes, distance_modulation=modulation)["raw_output"]
    rows = _rows(raw, processed, result)
    run_dir = Path(output_root) / "run_20261115_symmetric_reciprocal"
    run_dir.mkdir(parents=True, exist_ok=False)
    _write_outputs(run_dir, rows, inputs, raw, processed, result, modulation, report)
    return run_dir


def main() -> None:
    """Expose one bounded real-IFC diagnostic replay command."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--output-root", type=Path, default=OUTPUT)
    args = parser.parse_args()
    print(json.dumps({"status": "complete", "run_dir": str(run(args.output_root).resolve())}, sort_keys=True))


if __name__ == "__main__":
    main()
